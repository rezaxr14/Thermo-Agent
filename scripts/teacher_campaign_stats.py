# Short, stable failure classes.  Order matters: first match wins.
_ERROR_RULES: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("auth:missing_proxy", ("model_proxy_url", "model_proxy_api_key", "missing environment variables")),
    ("auth:invalid", ("unauthorized", "401", "forbidden", "403", "authentication failed", "invalid api key")),
    ("api:rate_limit", ("rate limit", "429", "resource_exhausted", "quota", "too many requests")),
    ("api:timeout", ("timeouterror", "timed out", "timeout", "deadline exceeded")),
    ("api:bad_request", ("badrequest", "invalid_request_error", "error code: 400", "error code: 422")),
    ("api:server_error", ("500", "502", "503", "internal server error", "service unavailable")),
    ("tools:limit", ("tool limit", "tool_limit", "toollimit", "max tool")),
    ("parse:no_xml", ("no xml", "parse", "unparseable", "invalid xml", "could not parse")),
    ("budget:exhausted", ("daily quota", "budget exhausted", "out of credits")),
)

_REASON_PREFIX = {
    "format": "parse",
    "edit": "edit",
    "verifier": "solver",
    "grounding": "grounding",
    "ranking": "ranking",
    "prediction": "prediction",
    "change": "change",
    "closure": "closure",
    "nonneg": "nonneg",
    "exact": "exact",
    "plant": "plant",
    "reward": "reward",
}

_SECRET_RE = re.compile(
    r"(?i)\b(api[_-]?key|token|secret|password|authorization)\b\s*[:=]\s*['\"]?[^\s,'\"}\]]+"
)
_KEY_RE = re.compile(r"\b(sk|pk)-[A-Za-z0-9_-]{12,}")
_GENERATED_RE = re.compile(r"Generated\s+(\S+)")


def utc_now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def redact(text: Any) -> str:
    """Collapse a raw reason to one log-safe line, redacting obvious credentials."""
    if text is None:
        return ""
    out = str(text).replace("\r", " ").replace("\n", " ").replace("\t", " ")
    out = _SECRET_RE.sub(lambda m: f"{m.group(1)}=<redacted>", out)
    out = _KEY_RE.sub("<redacted-key>", out)
    out = re.sub(r"\s+", " ", out).strip()
    return out[:400]


def classify_error(text: str) -> str:
    """Map a raw driver/API error string to a short failure class."""
    low = text.lower()
    for klass, needles in _ERROR_RULES:
        if any(n in low for n in needles):
            return klass
    # Last resort: keep the exception type, which is still a useful short class.
    first = re.split(r"[:\n]", text.strip(), maxsplit=1)[0].strip()
    if first and re.fullmatch(r"[\w.]{1,40}", first):
        return f"error:{first}"
    return "error:other"


def classify_reason(text: str) -> str:
    """Map a verifier/memory reason to a short failure class."""
    raw = text.strip()
    if not raw:
        return "other:empty"
    head, sep, tail = raw.partition(":")
    key = head.strip().lower()
    detail = tail.strip().lower() if sep else ""

    # Solver/verifier codes are the most informative class we have.
    code = re.search(r"\b(E_[A-Z0-9_]+|V\d+_[A-Za-z0-9_]+)\b", raw)
    if code:
        return f"solver:{code.group(1)}"

    if key in ("format", "parse", "xml"):
        if not detail or "no parseable" in detail or "no xml" in detail or "unparseable" in detail:
            return "parse:no_xml"
        if "empty" in detail:
            return "parse:empty_block"
        if "unknown" in detail or "component id" in detail:
            return "parse:unknown_id"
        if "block" in detail or "need <" in detail:
            return "parse:missing_blocks"
        return "parse:other"
    if key in ("edit",):
        return "edit:invalid"
    if key in ("verifier", "solver"):
        return "solver:invalid_plant"
    if key in ("grounding",):
        return "grounding:low"
    if key in ("ranking",):
        return "ranking:low_ndcg"
    if key in ("prediction",):
        if "no usable" in detail:
            return "prediction:missing"
        return "prediction:error_high"
    if key in ("change",):
        return "change:invalid"
    if key in ("closure", "nonneg", "exact", "plant"):
        return f"{key}:failed"
    if key in ("reward",):
        return "reward:below_threshold"
    if key in ("auth", "authentication"):
        return "auth:missing_proxy" if "proxy" in detail else "auth:invalid"
    if key in ("api",):
        return classify_error(raw)
    if raw.startswith("Attempt rejected"):
        # The memory notes wrap the real reason in parentheses after the first
        # colon, so inspect the whole lesson rather than only ``detail``.
        low = raw.lower()
        if "unknown component" in low or "unknown id" in low:
            return "parse:unknown_id"
        if "blocks" in low or "need <" in low:
            return "parse:missing_blocks"
        if "grounding" in low:
            return "grounding:low"
        if "relative error" in low:
            return "prediction:error_high"
        if "no usable prediction" in low:
            return "prediction:missing"
        if "change" in low:
            return "change:invalid"
        if "prediction" in low:
            return "prediction:error_high"
        return "verifier:rejected"
    if re.fullmatch(r"[A-Za-z][\w.-]{0,24}", head):
        return f"{key}:other"
    return "other:unknown"


def failure_signals(row: dict[str, Any]) -> list[str]:
    """All raw failure strings on a row, most diagnostic first."""
    out: list[str] = []
    error = row.get("error")
    if isinstance(error, dict):
        error = error.get("message") or error.get("text") or str(error)
    if error:
        out.append(str(error))

    verdict = row.get("verdict")
    if isinstance(verdict, dict):
        failed = verdict.get("failed") or []
        if isinstance(failed, str):
            failed = [failed]
        for item in failed:
            out.append(str(item))
        for reason in verdict.get("reasons") or []:
            if reason:
                out.append(str(reason))
    else:
        for reason in row.get("reasons") or []:
            if reason:
                out.append(str(reason))

    if row.get("tool_limit_exhausted"):
        out.append("tool limit exhausted")
    return out


def failure_class(row: dict[str, Any]) -> str | None:
    """The single primary failure class for a rejected row."""
    signals = failure_signals(row)
    if not signals:
        return "other:no_reason"
    raw = signals[0]
    if raw.lower().startswith(("valueerror", "timeouterror", "badrequest", "importerror", "httperror")):
        return classify_error(raw)
    return classify_reason(raw)


ACCEPTED = "accepted"
REJECTED = "rejected"
UNGRADED = "ungraded"


def classify_row(row: dict[str, Any]) -> str:
    """Return ``accepted`` / ``rejected`` / ``ungraded`` for one journal row.

    A completion is never evidence of acceptance: hosted-task rows are graded
    later at ingest and arrive with ``verdict.accepted = None, graded = False``.
    Classification order:

    1. ``error`` present                          -> rejected (reason from error)
    2. ``verdict.graded`` false, or an explicit
       ``verdict.accepted = None``               -> ungraded
    3. ``verdict.accepted is True / False``      -> accepted / rejected
    4. explicit top-level ``accepted`` flag      -> accepted / rejected (None -> ungraded)
    5. no verdict and no flag                    -> ungraded
    """
    if row.get("error"):
        return REJECTED
    verdict = row.get("verdict")
    if isinstance(verdict, dict):
        if "graded" in verdict and not verdict["graded"]:
            return UNGRADED
        if "accepted" in verdict:
            value = verdict["accepted"]
            if value is None:
                return UNGRADED
            return ACCEPTED if value is True else REJECTED
        # A verdict without an accepted flag is not proof of acceptance either.
        return UNGRADED
    if "accepted" in row:
        value = row["accepted"]
        if value is None:
            return UNGRADED
        return ACCEPTED if value is True else REJECTED
    return UNGRADED


def iter_tool_calls(row: dict[str, Any]) -> Iterable[str]:
    """Yield names of *actual* tool invocations (not merely the allowed tool list)."""
    calls = row.get("tool_calls") or []
    if isinstance(calls, dict):
        calls = [calls]
    traj = row.get("trajectory")
    if isinstance(traj, dict):
        calls = list(calls) + list(traj.get("tool_calls") or [])
        for turn in traj.get("turns") or []:
            if isinstance(turn, dict):
                calls = list(calls) + list(turn.get("tool_calls") or [])
    for call in calls:
        if isinstance(call, dict):
            name = call.get("name") or call.get("tool") or call.get("function")
            if isinstance(name, dict):
                name = name.get("name")
            if name:
                yield str(name)
        elif isinstance(call, str) and call:
            yield call


def has_thinking(row: dict[str, Any]) -> bool:
    """Whether the row carries any reasoning / thinking content."""
    for key in ("reasoning", "thinking", "thought"):
        if row.get(key):
            return True
    traj = row.get("trajectory")
    if isinstance(traj, dict):
        for key in ("reasoning", "thinking", "thought", "sft_completion"):
            if traj.get(key):
                return True
        for turn in traj.get("turns") or []:
            # The visible assistant prose is the reasoning trace for chat-completions
            # models; counting only "reasoning" reported these traces as thinking-free.
            if isinstance(turn, dict) and any(
                    turn.get(k) for k in ("reasoning", "thinking", "thought", "assistant")):
                return True
    completion = str(row.get("completion") or "")
    return "<thinking>" in completion or "<analysis>" in completion


def _as_int(value: Any) -> int:
    try:
        return int(value or 0)
    except (TypeError, ValueError):
        return 0


def usage_of(row: dict[str, Any]) -> dict[str, int]:
    u = row.get("usage") or {}
    if not isinstance(u, dict):
        u = {}
    return {
        "input_tokens": _as_int(u.get("input_tokens")),
        "output_tokens": _as_int(u.get("output_tokens")),
        "cost_nanodollars": _as_int(u.get("total_cost_nanodollars") or u.get("cost_nanodollars")),
        "latency_ms": _as_int(u.get("total_backend_latency_ms") or u.get("latency_ms")),
    }


def load_journals(runs_dir: Path) -> tuple[list[dict[str, Any]], list[str], int]:
    """Read all top-level ``*.jsonl`` journals; return (rows, file names, malformed count)."""
    rows: list[dict[str, Any]] = []
    names: list[str] = []
    malformed = 0
    paths = sorted(p for p in runs_dir.glob("*.jsonl") if p.is_file())
    for path in paths:
        names.append(path.name)
        with path.open("r", encoding="utf-8", errors="replace") as fh:
            for line in fh:
                if not line.strip():
                    continue
                try:
                    row = json.loads(line)
                except (ValueError, TypeError):
                    malformed += 1
                    continue
                if isinstance(row, dict):
                    rows.append(row)
                else:
                    malformed += 1
    return rows, names, malformed


def _bucket() -> dict[str, int]:
    return {"rows": 0, "accepted": 0, "rejected": 0, "ungraded": 0,
            "graded_by_ingest": 0, "accepted_ingest": 0, "rejected_ingest": 0,
            "tool_calls": 0, "input_tokens": 0, "output_tokens": 0, "cost_nanodollars": 0}


def _bump(bucket: dict[str, int], row: dict[str, Any], status: str, tool_calls: list[str],
          from_ingest: bool = False) -> None:
    usage = usage_of(row)
    bucket["rows"] += 1
    bucket[status] += 1
    if from_ingest:
        bucket["graded_by_ingest"] += 1
        bucket["accepted_ingest" if status == ACCEPTED else "rejected_ingest"] += 1
    bucket["tool_calls"] += len(tool_calls)
    bucket["input_tokens"] += usage["input_tokens"]
    bucket["output_tokens"] += usage["output_tokens"]
    bucket["cost_nanodollars"] += usage["cost_nanodollars"]


def _rate(accepted: int, graded: int) -> float | None:
    """Acceptance rate over graded rows only; None when nothing has been graded."""
    return round(accepted / graded, 4) if graded else None


def _fmt_rate(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.1%}"


def _raw_bucket() -> dict[str, Any]:
    return {"count": 0, "examples": [], "_seen": set()}


def add_raw(target: dict[str, dict[str, Any]], klass: str, raw: str, cap: int = 12) -> None:
    entry = target.setdefault(klass, _raw_bucket())
    entry["count"] += 1
    seen: set[str] = entry["_seen"]
    if raw not in seen and len(entry["examples"]) < cap:
        seen.add(raw)
        entry["examples"].append(raw)


def read_memory(memory_path: Path) -> tuple[Counter[str], dict[str, dict[str, Any]]]:
    """Aggregate the optional failure-memory summary into short classes."""
    counts: Counter[str] = Counter()
    raw: dict[str, dict[str, Any]] = {}
    if not memory_path.exists():
        return counts, raw
    try:
        data = json.loads(memory_path.read_text(encoding="utf-8"))
    except (ValueError, OSError):
        return counts, raw
    if not isinstance(data, dict):
        return counts, raw

    for lesson in data.get("top_lessons") or []:
        if not isinstance(lesson, dict):
            continue
        text = str(lesson.get("lesson") or "")
        n = _as_int(lesson.get("count"))
        if not text or not n:
            continue
        klass = classify_reason(text)
        counts[klass] += n
        add_raw(raw, klass, redact(text))
    # by_fault_type is keyed by fault code; fold those in too when they are non-empty.
    for fault, n in (data.get("by_fault_type") or {}).items():
        if not fault or not _as_int(n):
            continue
        klass = classify_reason(str(fault))
        counts[klass] += _as_int(n)
        add_raw(raw, klass, str(fault))
    return counts, raw


# --- ingest reports -----------------------------------------------------------
# transfer.py::ingest returns an AGGREGATE report (transfer.py lines 237-240):
#   {"model", "attempts", "accepted", "rejected",
#    "stats": {"accepted:<task>", "rejected:<task>", "reason:<prefix>", ...},
#    "failure_reasons": {"n", "by_task", "by_fault_type", "top_lessons": [...]},
#    "usage": {"models": {...}, ...}}
# It carries no record ids, so aggregate counts are attributed to ungraded
# journal rows of the same (model, task) in journal order.  Reports that also
# carry per-id lists (accepted_ids / rejected_ids / records / results ...) grade
# those exact ids instead, which always beats a deferred journal verdict.
INGEST_PATTERNS = ("logs/ingest_*.json", "data/teacher_runs/**/*ingest*.json")
_PER_ID_KEYS = ("accepted_ids", "rejected_ids", "accepted_records", "rejected_records",
                "results", "records", "rows", "decisions", "verdicts", "grades")
_MODEL_SUFFIX_RE = re.compile(r"-t-[A-Za-z0-9._-]+$")
_EXCEPTION_PREFIXES = ("valueerror", "timeouterror", "badrequest", "importerror", "httperror")


def discover_ingest_reports(root: Path) -> list[Path]:
    """Find reports under logs/ and data/teacher_runs/**, deduped by resolved path."""
    found: dict[Path, Path] = {}
    for pattern in INGEST_PATTERNS:
        for path in root.glob(pattern):
            if path.is_file():
                found.setdefault(path.resolve(), path)
    return [found[key] for key in sorted(found, key=lambda p: str(p).lower())]


def _load_report(text: str) -> dict[str, Any] | None:
    """Parse a report, tolerating tee'd stdout with surrounding log lines."""
    candidates = [text.strip()]
    start, end = text.find("{"), text.rfind("}")
    if start >= 0 and end > start:
        candidates.append(text[start:end + 1])
    candidates += [line.strip() for line in text.splitlines() if line.strip().startswith("{")]
    for candidate in candidates:
        try:
            data = json.loads(candidate)
        except (ValueError, TypeError):
            continue
        if isinstance(data, dict):
            return data
    return None


def _id_variants(value: Any) -> list[str]:
    """Exact id, base id before ``#vN``, and base id without the ``-t-<model>`` tag."""
    text = str(value or "").strip()
    out: list[str] = []

    def add(item: str) -> None:
        if item and item not in out:
            out.append(item)

    add(text)
    base = text.split("#", 1)[0]
    add(base)
    add(_MODEL_SUFFIX_RE.sub("", base))
    return out


def classify_failure_text(raw: str) -> str:
    return classify_error(raw) if raw.lower().startswith(_EXCEPTION_PREFIXES) else classify_reason(raw)


def _decision_from_item(item: Any, status_hint: str | None) -> dict[str, str] | None:
    if isinstance(item, str):
        rid = item.strip()
        status = status_hint
        task = model = reason = ""
    elif isinstance(item, dict):
        rid = str(item.get("id") or item.get("record_id") or item.get("recordId") or "").strip()
        status = status_hint
        for key in ("accepted", "verdict", "grade"):
            value = item.get(key)
            if isinstance(value, dict):
                value = value.get("accepted")
            if value is True:
                status = ACCEPTED
                break
            if value is False:
                status = REJECTED
                break
        task = str(item.get("task") or "")
        model = str(item.get("model") or "")
        raw_reason = item.get("reason") or item.get("error") or item.get("failure_reason") or ""
        if isinstance(raw_reason, dict):
            raw_reason = raw_reason.get("message") or str(raw_reason)
        reason = redact(raw_reason)
    else:
        return None
    if not rid or status not in (ACCEPTED, REJECTED):
        return None
    return {"id": rid, "status": status, "task": task, "model": model, "reason": reason}


def parse_ingest_report(path: Path, root: Path) -> dict[str, Any] | None:
    """Parse one report defensively; return None for malformed / unusable files."""
    try:
        data = _load_report(path.read_text(encoding="utf-8", errors="replace"))
    except OSError:
        return None
    if data is None:
        return None

    stats = data.get("stats") if isinstance(data.get("stats"), dict) else {}
    usage = data.get("usage") if isinstance(data.get("usage"), dict) else {}
    models = usage.get("models") if isinstance(usage.get("models"), dict) else {}
    model = str(data.get("model") or "")
    if not model and models:
        model = str(max(models, key=lambda key: _as_int(models[key])))

    per_task: dict[str, dict[str, int]] = {}
    reason_counts: Counter[str] = Counter()
    reason_examples: dict[str, str] = {}
    for key, value in stats.items():
        n = _as_int(value)
        if not n:
            continue
        if key.startswith(("accepted:", "rejected:")):
            status, task = key.split(":", 1)
            task = task.strip()
            if task:
                slot = per_task.setdefault(task, {"accepted": 0, "rejected": 0})
                slot["accepted" if status == "accepted" else "rejected"] += n
        elif key.startswith("reason:"):
            raw_reason = key.split(":", 1)[1]
            klass = classify_reason(raw_reason)
            reason_counts[klass] += n
            reason_examples.setdefault(klass, redact(raw_reason))

    accepted = _as_int(data.get("accepted")) or sum(v["accepted"] for v in per_task.values())
    rejected = _as_int(data.get("rejected")) or sum(v["rejected"] for v in per_task.values())

    fr = data.get("failure_reasons") if isinstance(data.get("failure_reasons"), dict) else {}
    lessons: list[dict[str, Any]] = []
    for lesson in fr.get("top_lessons") or []:
        if not isinstance(lesson, dict):
            continue
        text, n = str(lesson.get("lesson") or ""), _as_int(lesson.get("count"))
        if not text or not n:
            continue
        klass = classify_reason(text)
        reason_counts[klass] += n
        reason_examples.setdefault(klass, redact(text))
        lessons.append({"lesson": redact(text), "count": n})
    for fault, n in (fr.get("by_fault_type") or {}).items():
        if not fault or not _as_int(n):
            continue
        klass = classify_reason(str(fault))
        reason_counts[klass] += _as_int(n)
        reason_examples.setdefault(klass, str(fault))

    decisions: dict[str, dict[str, str]] = {}
    for key in _PER_ID_KEYS:
        value = data.get(key)
        if not isinstance(value, list):
            continue
        hint = ACCEPTED if key.startswith("accepted") else REJECTED if key.startswith("rejected") else None
        for item in value:
            decision = _decision_from_item(item, hint)
            if not decision:
                continue
            for variant in _id_variants(decision["id"]):
                decisions[variant] = decision

    name = (str(path.relative_to(root)).replace("\\", "/")
            if path.is_relative_to(root) else str(path))
    return {
        "name": name,
        "model": model,
        "attempts": _as_int(data.get("attempts")),
        "accepted": accepted,
        "rejected": rejected,
        "per_task": per_task,
        "reason_counts": dict(reason_counts),
        "reason_examples": reason_examples,
        "decisions": decisions,
        "lessons": lessons,
    }


def _lookup_decision(decisions: dict[str, dict[str, str]], row_id: Any) -> dict[str, str] | None:
    for variant in _id_variants(row_id):
        hit = decisions.get(variant)
        if hit:
            return hit
    return None


def build_stats(rows: list[dict[str, Any]], files: list[str], malformed: int,
                memory_path: Path, generated_at: str, root: Path,
                ingest_reports: list[dict[str, Any]] | None = None,
                ingest_skipped: list[str] | None = None) -> dict[str, Any]:
    totals = _bucket()
    per_model: dict[str, dict[str, int]] = defaultdict(_bucket)
    per_task: dict[str, dict[str, int]] = defaultdict(_bucket)
    per_model_task: dict[str, dict[str, dict[str, int]]] = defaultdict(
        lambda: defaultdict(_bucket)
    )
    failures: Counter[str] = Counter()
    failure_raw: dict[str, dict[str, Any]] = {}
    tool_counts: Counter[str] = Counter()
    rows_with_tool_calls = 0
    rows_with_thinking = 0

    ingest_reports = ingest_reports or []
    ingest_skipped = ingest_skipped or []
    decisions: dict[str, dict[str, str]] = {}
    for report in ingest_reports:
        decisions.update(report["decisions"])
    statuses = [classify_row(row) for row in rows]
    ingest_meta: list[dict[str, Any] | None] = [None] * len(rows)

    # A per-id ingest verdict overrides only a deferred journal row.  Rows that
    # are already graded (or that carry an error) keep their own verdict.
    for index, row in enumerate(rows):
        if statuses[index] != UNGRADED:
            continue
        decision = _lookup_decision(decisions, row.get("id"))
        if not decision:
            continue
        statuses[index] = decision["status"]
        ingest_meta[index] = {"kind": "per_id", "reason": decision["reason"],
                              "task": decision["task"], "model": decision["model"]}

    # Aggregate transfer.ingest reports carry no ids: attribute their counts to
    # ungraded rows of the same (model, task), in journal order, until exhausted.
    for report in ingest_reports:
        if report["decisions"]:
            # A report with per-id decisions is fully resolved by id; its top-level
            # counts are a summary of those decisions, not an extra set of rows.
            continue
        groups = ([(report["model"], task, counts["accepted"], counts["rejected"])
                   for task, counts in sorted(report["per_task"].items())]
                  if report["per_task"] else
                  [(report["model"], "", report["accepted"], report["rejected"])])
        for model, task, n_accepted, n_rejected in groups:
            candidates = [
                index for index, row in enumerate(rows)
                if statuses[index] == UNGRADED
                and (not model or str(row.get("model") or "") == model)
                and (not task or str(row.get("task") or "") == task)
            ]
            weighted: list[str] = []
            for klass, n in sorted(report["reason_counts"].items()):
                weighted.extend([klass] * min(_as_int(n), 2000))
            if not weighted:
                weighted = ["other:ingest_rejected"]
            for position, index in enumerate(candidates[: n_accepted + n_rejected]):
                status = ACCEPTED if position < n_accepted else REJECTED
                statuses[index] = status
                klass = weighted[(position - n_accepted) % len(weighted)] if status == REJECTED else ""
                ingest_meta[index] = {
                    "kind": "aggregate", "reason": "", "klass": klass,
                    "raw": report["reason_examples"].get(klass, ""),
                    "task": task, "model": model,
                }

    for index, row in enumerate(rows):
        model = str(row.get("model") or "unknown")
        task = str(row.get("task") or "unknown")
        meta = ingest_meta[index]
        if meta:
            if meta.get("model") and model == "unknown":
                model = str(meta["model"])
            if meta.get("task") and task == "unknown":
                task = str(meta["task"])
        status = statuses[index]
        calls = list(iter_tool_calls(row))
        from_ingest = meta is not None
        _bump(totals, row, status, calls, from_ingest)
        _bump(per_model[model], row, status, calls, from_ingest)
        _bump(per_task[task], row, status, calls, from_ingest)
        _bump(per_model_task[model][task], row, status, calls, from_ingest)

        if calls:
            rows_with_tool_calls += 1
            for name in calls:
                tool_counts[name] += 1
        if has_thinking(row):
            rows_with_thinking += 1

        if status == REJECTED:
            if meta and meta.get("klass"):
                klass = str(meta["klass"])
                failures[klass] += 1
                add_raw(failure_raw, klass, redact(meta.get("raw") or klass))
            elif meta and meta.get("reason"):
                klass = classify_failure_text(str(meta["reason"]))
                failures[klass] += 1
                add_raw(failure_raw, klass, str(meta["reason"]))
            else:
                klass = failure_class(row)
                failures[klass] += 1
                signals = failure_signals(row)
                add_raw(failure_raw, klass, redact(signals[0] if signals else "no reason given"))

    memory_counts, memory_raw = read_memory(memory_path)

    by_model_task: dict[str, dict[str, dict[str, int]]] = defaultdict(
        lambda: defaultdict(lambda: {"accepted": 0, "rejected": 0})
    )
    all_reason_classes: Counter[str] = Counter()
    for report in ingest_reports:
        all_reason_classes.update(report["reason_counts"])
        if report["per_task"]:
            for task, counts in report["per_task"].items():
                slot = by_model_task[report["model"] or "unknown"][task]
                slot["accepted"] += counts["accepted"]
                slot["rejected"] += counts["rejected"]
        else:
            slot = by_model_task[report["model"] or "unknown"]["unknown"]
            slot["accepted"] += report["accepted"]
            slot["rejected"] += report["rejected"]
    matched_ids = [str(rows[i].get("id")) for i, meta in enumerate(ingest_meta)
                   if meta and meta["kind"] == "per_id"]
    all_ids = {variant for row in rows for variant in _id_variants(row.get("id"))}
    unmatched_ids = sorted(set(decisions) - all_ids)[:50]

    per_model_out = {k: _finish_bucket(v) for k, v in sorted(per_model.items())}
    per_task_out = {k: _finish_bucket(v) for k, v in sorted(per_task.items())}
    per_model_task_out = {
        model: {task: _finish_bucket(b) for task, b in sorted(tasks.items())}
        for model, tasks in sorted(per_model_task.items())
    }
    for entry in failure_raw.values():
        entry.pop("_seen", None)
    for entry in memory_raw.values():
        entry.pop("_seen", None)

    cost_nano = totals["cost_nanodollars"]
    graded_rows = totals["accepted"] + totals["rejected"]
    stats: dict[str, Any] = {
        "generated_at": generated_at,
        "generated_by": "scripts/teacher_campaign_stats.py",
        "source": {
            "runs_dir": str(RUNS_REL).replace("\\", "/"),
            "journals": files,
            "journal_count": len(files),
            "memory_file": str(memory_path.relative_to(root)).replace("\\", "/")
            if memory_path.is_relative_to(root) else str(memory_path),
            "memory_file_found": memory_path.exists(),
            "malformed_lines": malformed,
            "rows": len(rows),
        },
        "totals": _finish_bucket(totals),
        "per_model": per_model_out,
        "per_task": per_task_out,
        "per_model_task": per_model_task_out,
        "failure_reasons": dict(failures.most_common()),
        "failure_reasons_raw": failure_raw,
        "memory_failure_reasons": dict(memory_counts.most_common()),
        "memory_failure_reasons_raw": memory_raw,
        "tool_call_counts": dict(tool_counts.most_common()),
        "rows_with_tool_calls": rows_with_tool_calls,
        "rows_with_thinking": rows_with_thinking,
        "graded_rows": graded_rows,
        "accepted_total": totals["accepted"],
        "rejected_total": totals["rejected"],
        "acceptance_rate": _rate(totals["accepted"], graded_rows),
        "acceptance_rate_denominator": "accepted_total + rejected_total (ungraded rows excluded)",
        "ingest_reports": {
            "files_read": [report["name"] for report in ingest_reports],
            "files_skipped": ingest_skipped,
            "report_count": len(ingest_reports),
            "graded_by_ingest": totals["graded_by_ingest"],
            "per_id_decisions": len(decisions),
            "matched_ids": len(matched_ids),
            "unmatched_ids": unmatched_ids,
            "model_task_counts": {
                model: {task: counts for task, counts in sorted(tasks.items())}
                for model, tasks in sorted(by_model_task.items())
            },
            "reason_classes": dict(sorted(all_reason_classes.items())),
            "reports": [
                {
                    "file": report["name"],
                    "model": report["model"],
                    "attempts": report["attempts"],
                    "accepted": report["accepted"],
                    "rejected": report["rejected"],
                    "per_task": report["per_task"],
                    "reason_classes": report["reason_counts"],
                    "top_lessons": report["lessons"],
                }
                for report in ingest_reports
            ],
        },
        "usage": {
            "input_tokens": totals["input_tokens"],
            "output_tokens": totals["output_tokens"],
            "total_tokens": totals["input_tokens"] + totals["output_tokens"],
            "cost_nanodollars": cost_nano,
            "cost_usd": round(cost_nano / 1e9, 9),
            "latency_ms": 0,  # filled below from totals bucket extension
        },
        "acceptance_rule": (
            "error -> rejected; verdict.graded false or explicit verdict.accepted null -> "
            "ungraded; verdict.accepted true/false -> accepted/rejected; explicit top-level "
            "accepted true/false -> accepted/rejected; otherwise ungraded. A completion "
            "without a verdict is never counted as accepted. An ingest verdict overrides a "
            "deferred (ungraded) journal row by record_id, or, for aggregate ingest reports, "
            "by (model, task) in journal order; a graded:true journal verdict always wins."
        ),
        "failure_class_rule": "one primary short class per rejected row; raw text only in JSON",
    }
    # latency is not part of the bucket table, sum it separately.
    stats["usage"]["latency_ms"] = sum(_as_int((r.get("usage") or {}).get(
        "total_backend_latency_ms") or (r.get("usage") or {}).get("latency_ms")) for r in rows)
    return stats


def _finish_bucket(bucket: dict[str, int]) -> dict[str, Any]:
    out = dict(bucket)
    out["graded_rows"] = out["accepted"] + out["rejected"]
    out["acceptance_rate"] = _rate(out["accepted"], out["graded_rows"])
    out["cost_usd"] = round(out["cost_nanodollars"] / 1e9, 9)
    out["total_tokens"] = out["input_tokens"] + out["output_tokens"]
    return out


def _md_cell(value: Any) -> str:
    return str(value).replace("|", "\\|").replace("\n", " ")


def snapshot_body(stats: dict[str, Any], generated_at: str) -> str:
    """The human-readable snapshot placed under 'Latest snapshot' (no heading)."""
    t = stats["totals"]
    u = stats["usage"]
    if t["ungraded"] and t["rows"]:
        ungraded_note = (
            f"_Ungraded rows today: **yes** — {t['ungraded']} of {t['rows']} "
            f"({t['ungraded'] / t['rows']:.1%}) are awaiting ingest-time grading._"
        )
    else:
        ungraded_note = "_Ungraded rows today: none._"
    ingest = stats["ingest_reports"]
    ingest_note = (
        f"_Ingest grading: {ingest['report_count']} report(s) read, "
        f"{len(ingest['files_skipped'])} skipped as malformed, "
        f"{t['graded_by_ingest']} journal rows resolved by ingest "
        f"({t['accepted_ingest']} accepted / {t['rejected_ingest']} rejected)._"
    )
    lines = [
        f"_Generated {generated_at} from {stats['source']['journal_count']} "
        f"journals ({t['rows']} rows)._",
        "",
        "| Metric | Value |",
        "| --- | ---: |",
        f"| Rows | {t['rows']} |",
        f"| Graded rows | {t['graded_rows']} |",
        f"| Accepted | {t['accepted']} |",
        f"| Rejected | {t['rejected']} |",
        f"| Ungraded | {t['ungraded']} |",
        f"| Graded by ingest | {t['graded_by_ingest']} |",
        f"| Accepted (ingest) | {t['accepted_ingest']} |",
        f"| Rejected (ingest) | {t['rejected_ingest']} |",
        f"| Acceptance rate (graded) | {_fmt_rate(t['acceptance_rate'])} |",
        f"| Rows with tool calls | {stats['rows_with_tool_calls']} |",
        f"| Rows with thinking | {stats['rows_with_thinking']} |",
        f"| Tool calls | {sum(stats['tool_call_counts'].values())} |",
        f"| Input tokens | {u['input_tokens']} |",
        f"| Output tokens | {u['output_tokens']} |",
        f"| Total tokens | {u['total_tokens']} |",
        f"| Cost (USD) | ${u['cost_usd']:.9f} |",
        f"| Malformed lines skipped | {stats['source']['malformed_lines']} |",
        "",
        "_Acceptance rate = accepted_total / (accepted_total + rejected_total), where "
        "accepted_total includes ingest-graded accepts; ungraded rows are excluded from "
        "the denominator._",
        ungraded_note,
        ingest_note,
        "",
        "### Per model",
        "",
        "| Model | Rows | Accepted | Rejected | Ungraded | Accepted (ingest) | Rejected (ingest) | Accept % (graded) | Tokens | Cost USD | Tool calls |",
        "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    if not stats["per_model"]:
        lines.append("| _(none)_ | 0 | 0 | 0 | 0 | 0 | 0 | n/a | 0 | 0 | 0 |")
    for model, m in sorted(stats["per_model"].items(), key=lambda kv: (-kv[1]["rows"], kv[0])):
        lines.append(
            f"| `{_md_cell(model)}` | {m['rows']} | {m['accepted']} | {m['rejected']} "
            f"| {m['ungraded']} | {m['accepted_ingest']} | {m['rejected_ingest']} "
            f"| {_fmt_rate(m['acceptance_rate'])} | {m['total_tokens']} "
            f"| {m['cost_usd']:.9f} | {m['tool_calls']} |"
        )
    lines += ["", "### Per task", "",
              "| Task | Rows | Accepted | Rejected | Ungraded | Accepted (ingest) | Rejected (ingest) | Accept % (graded) | Tokens | Cost USD | Tool calls |",
              "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    if not stats["per_task"]:
        lines.append("| _(none)_ | 0 | 0 | 0 | 0 | 0 | 0 | n/a | 0 | 0 | 0 |")
    for task, m in sorted(stats["per_task"].items(), key=lambda kv: (-kv[1]["rows"], kv[0])):
        lines.append(
            f"| `{_md_cell(task)}` | {m['rows']} | {m['accepted']} | {m['rejected']} "
            f"| {m['ungraded']} | {m['accepted_ingest']} | {m['rejected_ingest']} "
            f"| {_fmt_rate(m['acceptance_rate'])} | {m['total_tokens']} "
            f"| {m['cost_usd']:.9f} | {m['tool_calls']} |"
        )
    lines += ["", "### Failure reasons (short classes)", "",
              "| Class | Count |", "| --- | ---: |"]
    if not stats["failure_reasons"]:
        lines.append("| _(none)_ | 0 |")
    for klass, n in sorted(stats["failure_reasons"].items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f"| `{_md_cell(klass)}` | {n} |")
    if stats["memory_failure_reasons"]:
        lines += ["", "_Memory summary (from `data/memory/failure_reasons.json`):_", "",
                  "| Class | Count |", "| --- | ---: |"]
        for klass, n in sorted(stats["memory_failure_reasons"].items(),
                               key=lambda kv: (-kv[1], kv[0])):
            lines.append(f"| `{_md_cell(klass)}` | {n} |")
    lines += ["", "### Tool calls", "", "| Tool | Count |", "| --- | ---: |"]
    if not stats["tool_call_counts"]:
        lines.append("| _(none)_ | 0 |")
    for name, n in sorted(stats["tool_call_counts"].items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f"| `{_md_cell(name)}` | {n} |")
    return "\n".join(lines)


def split_sections(markdown: str) -> tuple[str, str]:
    """Return (latest_body, history_body) from an existing log, both may be empty."""
    i = markdown.find(LATEST_HEADING)
    j = markdown.find(HISTORY_HEADING)
    if i < 0 and j < 0:
        return "", ""
    if i < 0:
        return "", markdown[j + len(HISTORY_HEADING):].strip()
    if j < 0 or j < i:
        return markdown[i + len(LATEST_HEADING):].strip(), ""
    return (markdown[i + len(LATEST_HEADING):j].strip(),
            markdown[j + len(HISTORY_HEADING):].strip())


def snapshot_timestamp(body: str) -> str:
    match = _GENERATED_RE.search(body)
    return match.group(1) if match else "unknown"


def build_markdown(stats: dict[str, Any], previous: str, generated_at: str) -> str:
    """Build the append-friendly log: new Latest + all of the old Latest/History."""
    old_latest, old_history = split_sections(previous)
    parts = [LOG_HEADER.rstrip(), "", LATEST_HEADING, "", snapshot_body(stats, generated_at), "",
             HISTORY_HEADING, ""]
    if old_latest:
        parts += [f"### {snapshot_timestamp(old_latest)} — snapshot", "", old_latest, ""]
    if old_history:
        parts += [old_history, ""]
    return "\n".join(parts).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=ROOT, help="repository root")
    parser.add_argument("--runs-dir", type=Path, default=None)
    parser.add_argument("--memory-file", type=Path, default=None)
    parser.add_argument("--stats-out", type=Path, default=None)
    parser.add_argument("--log-out", type=Path, default=None)
    parser.add_argument("--generated-at", default=None, help="override the UTC timestamp (tests)")
    args = parser.parse_args(argv)

    root = args.root.resolve()
    runs_dir = (args.runs_dir or root / RUNS_REL).resolve()
    memory_file = (args.memory_file or root / MEMORY_REL).resolve()
    stats_out = (args.stats_out or root / STATS_REL).resolve()
    log_out = (args.log_out or root / LOG_REL).resolve()

    rows, files, malformed = load_journals(runs_dir)

    ingest_reports: list[dict[str, Any]] = []
    ingest_skipped: list[str] = []
    for path in discover_ingest_reports(root):
        report = parse_ingest_report(path, root)
        if report is None:
            ingest_skipped.append(str(path.relative_to(root)).replace("\\", "/")
                                  if path.is_relative_to(root) else str(path))
            continue
        ingest_reports.append(report)

    stats = build_stats(rows, files, malformed, memory_file,
                        args.generated_at or utc_now(), root,
                        ingest_reports=ingest_reports, ingest_skipped=ingest_skipped)

    stats_out.parent.mkdir(parents=True, exist_ok=True)
    stats_out.write_text(json.dumps(stats, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
                         encoding="utf-8")

    previous = log_out.read_text(encoding="utf-8") if log_out.exists() else ""
    log_out.parent.mkdir(parents=True, exist_ok=True)
    log_out.write_text(build_markdown(stats, previous, stats["generated_at"]), encoding="utf-8")

    t = stats["totals"]
    print(f"journals: {len(files)}  rows: {t['rows']}  accepted: {t['accepted']}  "
          f"rejected: {t['rejected']}  ungraded: {t['ungraded']}  graded: {t['graded_rows']}  "
          f"rate (accepted/graded): {_fmt_rate(t['acceptance_rate'])}")
    print(f"ingest reports: {len(ingest_reports)} read, {len(ingest_skipped)} skipped, "
          f"{t['graded_by_ingest']} rows graded by ingest")
    print(f"failure classes: {stats['failure_reasons']}")
    print(f"wrote {stats_out.relative_to(root) if stats_out.is_relative_to(root) else stats_out}")
    print(f"wrote {log_out.relative_to(root) if log_out.is_relative_to(root) else log_out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

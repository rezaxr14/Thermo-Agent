#!/usr/bin/env python3
"""Living statistics + records for the frontier teacher CoT campaign.

Reads every journal in ``data/teacher_runs/*.jsonl`` plus the optional
``data/memory/failure_reasons.json`` and writes two *outputs*:

* ``data/teacher_runs/CAMPAIGN_STATS.json`` -- machine-readable snapshot.
* ``reports/teacher_campaign_log.md``         -- human-readable, append-friendly log.

The markdown log is never rewritten destructively: on each run the previous
"Latest snapshot" is moved verbatim into "History" under its own timestamp and
the new snapshot is prepended under "Latest snapshot".  That gives the campaign
a running history across development without ever losing an earlier snapshot.

Rows are split into ``accepted`` / ``rejected`` / ``ungraded``; a completion with
no verdict is **ungraded**, never accepted.  Ingest reports in ``logs/ingest_*.json``
and ``data/teacher_runs/**/*ingest*.json`` grade deferred rows, by record id when
the report carries ids and by (model, task) for the aggregate ``transfer.ingest``
schema.  A ``graded:true`` journal verdict always wins.  The acceptance rate uses
only graded rows (``accepted_total / (accepted_total + rejected_total)``) and is
``null`` when none are graded.

Failure reasons are normalised to short classes (``auth:missing_proxy``,
``solver:E_PROP_RANGE``, ``parse:no_xml`` ...).  Raw reason text is kept **only**
in the JSON file (and redacted for obvious secrets); the markdown shows classes.

No network, no API calls, no Kaggle; standard library only.  Journals are
read-only: this script never writes to ``data/teacher_runs/*.jsonl``.

Run with:  .venv/Scripts/python.exe scripts/teacher_campaign_stats.py
"""


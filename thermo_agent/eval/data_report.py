"""python -m thermo_agent.eval.data_report DATA_DIR [--check-rows 20] : what is in the data, and does the reward pipeline accept it?
Run before training. Prints JSON; every 'problems' entry should be empty."""
from __future__ import annotations
import argparse, collections, json, pathlib, statistics as st


def _rows(d, task):
    out = {}
    for p in sorted(pathlib.Path(d).glob(f"{task}_*.jsonl")):
        out[p.stem[len(task) + 1:]] = [json.loads(l) for l in open(p)]
    return out


def _tokens(rows):
    n = [sum(len(m["content"]) for m in r["prompt"]) / 3.5 for r in rows]        # rough: 3.5 characters per token
    return {"mean": round(st.mean(n)), "max": round(max(n))} if n else None


def report(data_dir, check_rows=20) -> dict:
    from ..train import rewards as RR
    from ..design import rewards as DR
    from ..audit import rewards as AR
    from ..ledger import rewards as LR
    out, problems = {}, []
    for task, mod, cols in (("repair", RR, ("plant_broken", "plant_original", "site", "deducible", "min_edits")),
                            ("design", DR, ("site", "ref_fuel_w")), ("audit", AR, ("plant", "site", "ed_json", "fuel_w", "net_w", "best_gain_w")),
                            ("ledger", LR, ("ledger",))):
        splits = _rows(data_dir, task)
        if not splits: continue
        info = {"rows": {sp: len(v) for sp, v in splits.items()}}
        allrows = [r for v in splits.values() for r in v]
        info["approx_prompt_tokens"] = _tokens(allrows)
        if info["approx_prompt_tokens"] and info["approx_prompt_tokens"]["max"] > 2900: problems.append(f"{task}: prompts may exceed the SFT max_length of 3072 tokens")
        if task == "repair":
            info["fault_by_topology"] = dict(collections.Counter(f"{r['topology']}/{r['fault_type']}" for r in allrows))
            info["train_fault_types"] = sorted({r["fault_type"] for r in splits.get("train", [])})
        if task == "design":
            info["winning_configs"] = dict(collections.Counter("/".join(json.loads(r["ref_spec"])[k] for k in ("prime_mover", "cooling", "rejection", "bottoming")) for r in allrows).most_common(8))
            info["mean_valid_configs_per_site"] = round(st.mean(r["n_valid"] for r in allrows), 1)
        if task == "ledger":
            info["fault_type_counts"] = dict(collections.Counter(t for r in allrows for t in r["fault_types"]))
            info["train_fault_types"] = sorted({t for r in splits.get("train", []) for t in r["fault_types"]})
        if task == "audit":
            info["best_change_param"] = dict(collections.Counter(r["completion"][0]["content"].split("<change>")[1].split("=")[0].replace("SET", "").strip() for r in allrows).most_common(8))
        for need in ("train", "val", "test_id"):
            if need not in splits: problems.append(f"{task}: no '{need}' split (generate more rows)")
        sample = (splits.get("train") or allrows)[:check_rows]
        comps = [r["completion"][0]["content"] for r in sample]
        kw = {c: [r[c] for r in sample] for c in cols}
        scores = {}
        for f in mod.REWARD_FUNCS:
            v = [x for x in f(None, comps, **kw) if x is not None]
            scores[f.__name__] = round(st.mean(v), 3) if v else None
            if v and st.mean(v) < 0.95: problems.append(f"{task}: expert completions score {st.mean(v):.2f} on {f.__name__} (expected about 1)")
        info["expert_reward_means"] = scores
        out[task] = info
    import importlib.metadata as md
    metas = {p.stem[5:]: json.loads(p.read_text()) for p in pathlib.Path(data_dir).glob("meta_*.json")}
    out["meta"] = {t: {"params": m["params"], "coolprop": m["coolprop"], "created_utc": m["created_utc"]} for t, m in metas.items()}
    for t, m in metas.items():
        if m["coolprop"] != md.version("CoolProp"): problems.append(f"{t}: generated with CoolProp {m['coolprop']}, installed {md.version('CoolProp')}")
    for t in out:
        if t in ("repair", "design", "audit", "ledger") and t not in metas: problems.append(f"{t}: no meta_{t}.json (dataset was not generated by the current builders)")
    out["problems"] = problems
    return out


if __name__ == "__main__":
    ap = argparse.ArgumentParser(); ap.add_argument("data"); ap.add_argument("--check-rows", type=int, default=20)
    a = ap.parse_args(); print(json.dumps(report(a.data, a.check_rows), indent=1))
